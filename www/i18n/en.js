  var RE_C={b:'b',ch:'ch',d:'d',f:'f',g:'g',h:'h',j:'y',k:'k',l:'l',m:'m',n:'n',
            p:'p',r:'r',s:'s',sh:'sh',t:'t',th:'th',v:'v',w:'w',z:'z',
            c:'k',q:'k',x:'ks',y:'y'};
  function reC(str){ return splitC(str).map(function(c){ return RE_C[c]||c; }).join(''); }
  function reV(str){
    if(RE_V[str]) return RE_V[str];
    var out=[], i=0;
    while(i<str.length){
      var two=str.substr(i,2);
      if(two.length===2 && RE_V[two]){ out.push(RE_V[two]); i+=2; }
      else { out.push(RE_V[str[i]]||str[i]); i++; }
    }
    return out.join('-');
  }


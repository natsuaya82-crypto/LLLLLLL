  function word_en(ps){
    var out=[], i;
    for(i=0;i<ps.length;i++) out.push(syl_en(ps[i]));
    if(out.length) out[0]=out[0].toUpperCase();   /* stress falls on the first syllable */
    return out.join('-');
  }

